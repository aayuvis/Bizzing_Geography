const topicOf = Object.fromEntries(TOPICS.map((t) => [t.id, t]));
export const todaysWord = (day = dayKey()) => WORDS[Math.floor(seeded('word' + day)() * WORDS.length)];
const inDef = (w, d) => d.toLowerCase().includes(w.toLowerCase());

/* ten: a meaning, and four words from its topic, none of them spelled out in the meaning */
export function quiz(topic, r = rnd) {
  const pool = WORDS.filter(([, , t]) => !topic || t === topic);
  return shuffle(pool, r).slice(0, 10).map(([w, d, t, ex]) => {
    const same = WORDS.filter(([x, , tt]) => tt === t && x !== w && !inDef(x, d));
    return { ...mc(r, `Which word means: “${d}”?`, w, same.map((x) => x[0]), `${w}: ${d}.${ex ? ` Example: ${ex}.` : ''}`), text: `Which word means: “${d}”?` };
  });
}

