export function act(name, arg, ctx) {
  if (name === 'topic') ctx.ui.topic = arg || '';
  else if (name === 'quiz') ctx.startRun(`Dictionary quiz${ctx.ui.topic ? ' · ' + topicOf[ctx.ui.topic].name : ''}`, quiz(ctx.ui.topic || ''));
}
export function done(run) { const right = run.results.filter((x) => x.right).length; return { stars: right >= 9 ? 3 : right >= 7 ? 2 : 1, lines: [] }; }
export function selftest(ok) {
  const ws = WORDS.map((w) => w[0].toLowerCase());
  ok(WORDS.length >= 300, `at least 300 words (${WORDS.length})`);
  ok(new Set(ws).size === ws.length, 'no word twice');
  ok(ws.every((w, i) => !i || ws[i - 1].localeCompare(w) < 0), 'in alphabetical order');
  ok(WORDS.every(([w, d, t]) => w && d && topicOf[t]), 'every word has a meaning and a known topic');
  ok(WORDS.every(([w, d]) => !inDef(w, d)), 'no meaning contains its own word');
  for (const t of TOPICS) ok(WORDS.filter((x) => x[2] === t.id).length >= 12, `${t.name} has enough words for a quiz`);
  for (const t of ['', ...TOPICS.map((x) => x.id)]) {
    for (const q of quiz(t, seeded('dq' + t))) {
      ok(q.opts.length === 4 && q.opts.filter((o) => o === q.ans).length === 1, `quiz ${t || 'all'}: four choices, one right — ${q.ans}`);
      ok(!q.opts.some((o) => q.text.toLowerCase().includes(o.toLowerCase())), `quiz ${t || 'all'}: no choice is spelled out in the meaning — ${q.ans}`);
    }
  }
  ok(todaysWord('2026-01-01') === todaysWord('2026-01-01'), 'the word of the day is the same for everyone that day');
}
