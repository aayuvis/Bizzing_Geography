#!/usr/bin/env node
/* verify-streetview.mjs — which Where on Earth? places have Street View imagery.

   Asks Google's Street View METADATA endpoint (free: it costs no quota and
   returns no image) whether outdoor imagery exists within 5 km of each place
   in app/src/data/places.js, and writes the ids that do to
   app/src/data/sv-ok.js. The game then draws only from those, so a round
   never lands on an empty grey square.

   Only GOOGLE'S OWN panoramas are kept ("© Google" — shot by Google, faces
   and plates blurred). User-uploaded photospheres are skipped: they can be
   anyone's photo of anything, including people, and this is a children's
   app. The Static API has no filter for that, so the game is pinned to the
   verified panorama id. Nothing else is kept: no image, no coordinates.
   If the nearest panorama is a user's, up to sixteen nearby points are tried.

     GMAPS_KEY_FILE=/root/.gmapskey node verify-streetview.mjs
   The key is read from $GMAPS_KEY_FILE (default /root/.gmapskey). Never in the repo. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const KEYF = process.env.GMAPS_KEY_FILE || '/root/.gmapskey';
if (!fs.existsSync(KEYF)) { console.error(`no key at ${KEYF}`); process.exit(1); }
const KEY = fs.readFileSync(KEYF, 'utf8').trim();
const { PLACES } = await import(path.join(ROOT, 'app/src/data/places.js'));

const ok = {}, none = [], failed = [];
let userOnly = 0;
async function meta(lat, lng) {
  const u = `https://maps.googleapis.com/maps/api/streetview/metadata?location=${lat},${lng}&radius=5000&source=outdoor&key=${KEY}`;
  for (let t = 0; t < 4; t++) {
    try {
      const d = await (await fetch(u)).json();
      if (d.status === 'REQUEST_DENIED') { console.error('Google refused the key:', d.error_message || ''); process.exit(1); }
      if (d.status === 'OK' || d.status === 'ZERO_RESULTS' || d.status === 'NOT_FOUND') return d;
    } catch (e) { /* network — retry */ }
    await new Promise((r) => setTimeout(r, 500 * 2 ** t));
  }
  return null;
}
/* the place itself, then two rings of eight: ~2–3 km and ~8–9 km out */
const RING = [[0, 0], ...[0.025, 0.08].flatMap((r) => Array.from({ length: 8 }, (_, i) => [+(r * Math.cos(i * Math.PI / 4)).toFixed(4), +(r * Math.sin(i * Math.PI / 4)).toFixed(4)]))];
async function check(p) {
  let any = false;
  for (const [dy, dx] of RING) {
    const d = await meta(p.at[0] + dy, p.at[1] + dx);
    if (!d) return failed.push(p.id);
    if (d.status !== 'OK') continue;
    any = true;
    if (/google/i.test(d.copyright || '')) { ok[p.id] = d.pano_id; return; }
  }
  if (any) userOnly++; else none.push(p.id);
}
const queue = PLACES.slice();
await Promise.all(Array.from({ length: 12 }, async () => { while (queue.length) await check(queue.shift()); }));
if (failed.length > PLACES.length * 0.05) { console.error(`${failed.length} checks failed — not writing a partial answer`); process.exit(1); }
const ids = Object.keys(ok).sort();
fs.writeFileSync(path.join(ROOT, 'app/src/data/sv-ok.js'),
  `/* sv-ok.js — GENERATED by tools/geo/verify-streetview.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n   Places in places.js with a Google-shot Street View panorama near them, and that panorama's id. */\n` +
  `export const SV_PANO = ${JSON.stringify(Object.fromEntries(ids.map((i) => [i, ok[i]])))};\nexport const SV_OK = Object.keys(SV_PANO);\n`);
console.log(`street view: ${ids.length} of ${PLACES.length} places have Google imagery; ${userOnly} only user photospheres (skipped); ${none.length} none; ${failed.length} unchecked`);
if (ids.length < 1000) console.error(`WARNING: fewer than 1,000 verified places (${ids.length}) — widen the pool in places.mjs`);
