#!/usr/bin/env node
/* verify-streetview.mjs — which GeoGuesser places have Street View imagery.

   Asks Google's Street View METADATA endpoint (free: it costs no quota and
   returns no image) whether outdoor imagery exists within 5 km of each place
   in app/src/data/places.js, and writes the ids that do to
   app/src/data/sv-ok.js. The game then draws only from those, so a round
   never lands on an empty grey square.

   Nothing from Google is stored but a yes: no image, no panorama id, no
   coordinates — Google's terms do not allow caching their content, and a
   yes is all the game needs.

     GMAPS_KEY_FILE=/root/.gmapskey node verify-streetview.mjs
   The key is read from $GMAPS_KEY_FILE (default /root/.gmapskey). Never in the repo. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const KEYF = process.env.GMAPS_KEY_FILE || '/root/.gmapskey';
if (!fs.existsSync(KEYF)) { console.error(`no key at ${KEYF}`); process.exit(1); }
const KEY = fs.readFileSync(KEYF, 'utf8').trim();
const { PLACES } = await import(path.join(ROOT, 'app/src/data/places.js'));

const ok = [], none = [], failed = [];
async function check(p) {
  const u = `https://maps.googleapis.com/maps/api/streetview/metadata?location=${p.at[0]},${p.at[1]}&radius=5000&source=outdoor&key=${KEY}`;
  for (let t = 0; t < 4; t++) {
    try {
      const r = await fetch(u), d = await r.json();
      if (d.status === 'OK') return ok.push(p.id);
      if (d.status === 'ZERO_RESULTS' || d.status === 'NOT_FOUND') return none.push(p.id);
      if (d.status === 'REQUEST_DENIED') { console.error('Google refused the key:', d.error_message || ''); process.exit(1); }
    } catch (e) { /* network — retry */ }
    await new Promise((r) => setTimeout(r, 500 * 2 ** t));
  }
  failed.push(p.id);
}
const queue = PLACES.slice();
await Promise.all(Array.from({ length: 12 }, async () => { while (queue.length) await check(queue.shift()); }));
if (failed.length > PLACES.length * 0.05) { console.error(`${failed.length} checks failed — not writing a partial answer`); process.exit(1); }
ok.sort();
fs.writeFileSync(path.join(ROOT, 'app/src/data/sv-ok.js'),
  `/* sv-ok.js — GENERATED by tools/geo/verify-streetview.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n   Ids of places in places.js with outdoor Street View imagery within 5 km. */\n` +
  `export const SV_OK = ${JSON.stringify(ok)};\n`);
console.log(`street view: ${ok.length} of ${PLACES.length} places have imagery; ${none.length} none; ${failed.length} unchecked`);
if (ok.length < 1000) console.error(`WARNING: fewer than 1,000 verified places (${ok.length}) — widen the pool in places.mjs`);
